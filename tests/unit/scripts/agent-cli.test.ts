import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
	codeownersMatcher,
	evaluateReadiness,
	findAttribution,
	stripAttribution
} from '../../../scripts/agent-cli.mjs';

const BODY = `<!-- claude-projects-attribution: {"github_login":"stephennmiller"} -->
_Requested by **Steve** · [project thread](https://claude.ai/code/project/x)_

Fixes the thing.

Closes #1

---
_Generated by [Claude Code](https://claude.ai/code)_`;

describe('attribution', () => {
	it('finds the header, requested-by line and footer', () => {
		expect(findAttribution(BODY)).toHaveLength(3);
		expect(
			findAttribution('Co-Authored-By: Claude <noreply@anthropic.com>')
		).toHaveLength(1);
		expect(findAttribution('Claude Code is the AI backend')).toEqual([]);
	});

	it('strips them with the separator before the footer', () => {
		expect(stripAttribution(BODY)).toBe('Fixes the thing.\n\nCloses #1');
	});

	it('keeps a --- rule that separates real content', () => {
		expect(stripAttribution('a\n\n---\n\nb')).toBe('a\n\n---\n\nb');
	});
});

describe('codeownersMatcher', () => {
	const isOwned = codeownersMatcher(readFileSync('.github/CODEOWNERS', 'utf8'));

	it('matches directories, anchored files, globs and bare names anywhere', () => {
		expect(isOwned('.github/workflows/ci.yml')).toBe(true);
		expect(isOwned('apps/cli/src/commands/upgrade.command.ts')).toBe(true);
		expect(
			isOwned(
				'packages/tm-core/src/modules/ai/providers/claude-code-path-guard.ts'
			)
		).toBe(true);
		expect(isOwned('apps/cli/package.json')).toBe(true);
		expect(isOwned('package-lock.json')).toBe(true);
	});

	it('leaves other paths alone', () => {
		expect(isOwned('apps/cli/src/commands/list.command.ts')).toBe(false);
		expect(isOwned('packages/tm-core/src/modules/ai/providers/other.ts')).toBe(
			false
		);
		expect(isOwned('docs/github/workflows.md')).toBe(false);
	});
});

describe('evaluateReadiness', () => {
	const pr = {
		head: { sha: 'abc123' },
		number: 7,
		title: 't',
		state: 'open',
		mergeable: true,
		mergeable_state: 'clean',
		body: 'x'
	};
	const passed = [{ name: 'Test', status: 'completed', conclusion: 'success' }];
	const marker = (sha: string) => `\n\n<!-- claude-review sha=${sha} -->`;
	const reviewed = [{ body: `No issues. Round 2.${marker('abc123')}` }];
	const base = {
		pr,
		checks: passed,
		botComments: reviewed,
		files: ['a.ts'],
		isOwned: () => false
	};

	it('is ready when every rule passes', () => {
		expect(evaluateReadiness(base)).toMatchObject({ ready: true, reasons: [] });
	});

	it('lists each reason it is not', () => {
		const result = evaluateReadiness({
			pr: { ...pr, mergeable: false, body: BODY },
			checks: [
				...passed,
				{ name: 'Smoke', status: 'completed', conclusion: 'failure' }
			],
			botComments: [
				{ body: `No issues.${marker('abc123')}` },
				{ body: `2 issues. Round 2.${marker('abc123')}` }
			],
			files: ['package.json'],
			isOwned: (f: string) => f === 'package.json'
		});

		expect(result.ready).toBe(false);
		expect(result.reasons).toEqual([
			'merge conflict, run agent-cli rebase',
			'checks failed: Smoke',
			'review: 2 issues. Round 2.',
			'CODEOWNERS paths, Steve merges: package.json',
			'attribution in PR body, run agent-cli attribution'
		]);
	});

	it('is not ready before checks or review exist', () => {
		expect(
			evaluateReadiness({ ...base, checks: [], botComments: [] }).reasons
		).toEqual(['no checks have run', 'no review bot comment yet']);
	});

	it('ignores a review of an older commit and non-review bot comments (#913)', () => {
		const result = evaluateReadiness({
			...base,
			botComments: [
				{ body: `No issues. Round 1.${marker('def456')}` },
				{ body: 'Stopping reviews on this PR.' }
			]
		});

		expect(result.reasons).toEqual([
			'review bot has not reviewed the latest commit'
		]);
	});
});
